// Helper: parse sets from reps string (e.g. "3 × 12" → 3, "2 × 12" → 2)
function parseSets(reps: string): number {
  const m = reps.match(/^(\d+)\s*[×x]/);
  return m ? Number(m[1]) : 3;
}

// Helper: parse repsTarget from reps string (e.g. "3 × 12" → "12", "3 × até 20s" → "até 20s")
function parseRepsTarget(reps: string): string {
  const m = reps.match(/^(\d+)\s*[×x]\s*(.+)$/);
  return m ? m[2].trim() : reps;
}

